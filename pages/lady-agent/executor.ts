import { TaskState } from "@a2a-js/sdk";
import {
  AgentEvent,
  type AgentExecutor,
  type ExecutionEventBus,
  type RequestContext,
} from "@a2a-js/sdk/server";

import { extractTextFromParts } from "../../lib/agents/message";
import { makeRag } from "../../pages/api/rag";
import { getVectorStore } from "../../pages/api/vectorstore";

export const ladyAhorroAgentExecutor: AgentExecutor = {
  execute: async (
    requestContext: RequestContext,
    eventBus: ExecutionEventBus,
  ): Promise<void> => {
    const { taskId, contextId } = requestContext;

    const question = extractTextFromParts(requestContext.userMessage.parts);

    eventBus.publish(
      AgentEvent.task({
        id: taskId,
        contextId,
        status: {
          state: TaskState.TASK_STATE_WORKING,
          message: undefined,
          timestamp: new Date().toISOString(),
        },
        artifacts: [],
        history: [requestContext.userMessage],
        metadata: undefined,
      }),
    );

    const vectorStore = await getVectorStore();
    const rag = await makeRag(vectorStore);
    const answer = await rag(question);

    eventBus.publish(
      AgentEvent.artifactUpdate({
        taskId,
        contextId,
        artifact: {
          artifactId: `${taskId}-answer`,
          name: "Lady Ahorro answer",
          description: "Answer generated by the Lady Ahorro specialist.",
          parts: [
            {
              content: {
                $case: "text",
                value: answer,
              },
              metadata: undefined,
              filename: "",
              mediaType: "text/plain",
            },
          ],
          metadata: undefined,
          extensions: [],
        },
        append: false,
        lastChunk: true,
        metadata: undefined,
      }),
    );

    eventBus.publish(
      AgentEvent.statusUpdate({
        taskId,
        contextId,
        status: {
          state: TaskState.TASK_STATE_COMPLETED,
          message: undefined,
          timestamp: new Date().toISOString(),
        },
        metadata: undefined,
      }),
    );
  },

  cancelTask: async (
    taskId: string,
    eventBus: ExecutionEventBus,
  ): Promise<void> => {
    console.log("Cancel requested:", taskId);
  },
};